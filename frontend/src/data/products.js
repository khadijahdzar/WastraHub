/**
 * Filter produk — category/region pakai slug atau nama (cocok dengan SQL).
 * technique: tulis | cap | premium | modern (atau nama penuh).
 */
export function filterProducts({ category, region, technique, search, sort } = {}) {
  let result = [...products];

  if (category) {
    const cat = String(category).toLowerCase().replace(/-/g, " ");
    result = result.filter((p) => {
      const name = (p.category || "").toLowerCase();
      const slug = name.replace(/\s+/g, "-");
      return (
        name === cat ||
        slug === String(category).toLowerCase() ||
        name.includes(cat) ||
        slug.includes(String(category).toLowerCase())
      );
    });
  }

  if (region) {
    const r = String(region).toLowerCase();
    result = result.filter((p) => {
      const name = (p.region || "").toLowerCase();
      return name === r || name.replace(/\s+/g, "-") === r;
    });
  }

  if (technique) {
    const tech = String(technique)
      .toLowerCase()
      .replace(/^batik\s+/, "")
      .replace(/-/g, " ");
    result = result.filter((p) => {
      const t = (p.technique || p.type || "").toLowerCase().replace(/^batik\s+/, "");
      return t === tech || t.includes(tech);
    });
  }

  if (search) {
    const q = String(search).toLowerCase();
    result = result.filter(
      (p) =>
        p.name.toLowerCase().includes(q) ||
        (p.region || "").toLowerCase().includes(q) ||
        (p.category || "").toLowerCase().includes(q) ||
        (p.technique || "").toLowerCase().includes(q) ||
        (p.material || "").toLowerCase().includes(q) ||
        (p.description || "").toLowerCase().includes(q)
    );
  }

  if (sort === "price-asc") result.sort((a, b) => a.price - b.price);
  else if (sort === "price-desc") result.sort((a, b) => b.price - a.price);
  else if (sort === "name") result.sort((a, b) => a.name.localeCompare(b.name));
  else if (sort === "rating") result.sort((a, b) => (b.rating || 0) - (a.rating || 0));
  else if (sort === "featured")
    result.sort((a, b) => Number(b.isFeatured) - Number(a.isFeatured));

  return result;
}
